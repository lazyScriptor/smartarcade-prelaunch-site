#!/usr/bin/env node
// Splits the generated Daraz data so phones don't download every description up front:
//   src/data/catalogIndex.ts          light list used by cards, search and the cart (in the main bundle)
//   public/data/products/<id>.json    photos, description and highlights, fetched on the product page
// Re-run after import_daraz_catalog.py or import_client_price_file.py: npm run catalog
import fs from 'node:fs'
import path from 'node:path'

const SITE = path.resolve(import.meta.dirname, '..')
const read = (file, name) =>
  JSON.parse(fs.readFileSync(path.join(SITE, 'src/data', file), 'utf8').split(`export const ${name}: DarazCatalogRecord[] = `)[1])
const records = [...read('darazCatalog.ts', 'darazCatalog'), ...read('darazCatalogExtra.ts', 'darazCatalogExtra')]
  .filter(item => (item.nameEn || item.nameSi) && item.cardImage)

const clean = text => text.replace(/​/g, '').replace(/\s+/g, ' ').trim()
const index = records.map(item => {
  const name = clean(item.nameEn || item.nameSi)
  const nameSi = clean(item.nameSi)
  return {
    id: String(item.id),
    name,
    ...(nameSi && nameSi !== name ? { nameSi } : {}),
    cardImage: item.cardImage,
    ...(item.warrantyPeriod ? { warrantyPeriod: item.warrantyPeriod } : {}),
    ...(item.warrantyType ? { warrantyType: item.warrantyType } : {}),
  }
})

fs.writeFileSync(
  path.join(SITE, 'src/data/catalogIndex.ts'),
  `// Generated by scripts/build-catalog-index.mjs. Do not edit by hand.\n` +
    `export interface CatalogIndexRecord {\n  id: string\n  name: string\n  nameSi?: string\n  cardImage: string\n  warrantyPeriod?: string\n  warrantyType?: string\n}\n\n` +
    `export const catalogIndex: CatalogIndexRecord[] = ${JSON.stringify(index)}\n`,
)

const dir = path.join(SITE, 'public/data/products')
fs.rmSync(dir, { recursive: true, force: true })
fs.mkdirSync(dir, { recursive: true })
for (const item of records) {
  fs.writeFileSync(
    path.join(dir, `${item.id}.json`),
    JSON.stringify({ images: item.images, description: item.description, highlights: item.highlights, warrantyPolicy: item.warrantyPolicy }),
  )
}
console.log(`Indexed ${index.length} products.`)
